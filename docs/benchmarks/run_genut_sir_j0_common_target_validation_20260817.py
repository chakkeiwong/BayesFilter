os.environ.setdefault("TF_FORCE_GPU_ALLOW_GROWTH", "true")
ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
import tensorflow as tf

THETA_VALUES = (0.0, 0.0, 0.0)
N = 8192
CLAIM_SEEDS = tuple(range(97701, 97717))
CLASSIFIER_ROOT = ROOT / "docs/benchmarks/artifacts/classifier_score_variance_reduction_20260815/sir_full"
GENUT_RAW = ROOT / ".claude/worktrees/genut-guided-initialization/docs/benchmarks/artifacts/genut_repaired_hilbert_permutation_all_models_n1008_20260811/claim_attempt02/raw.json"
LGSSM_ORACLE = ROOT / "docs/benchmarks/artifacts/genut-score-validation-readiness-20260817/phase2_lgssm_oracle/result.json"
GAUSSIAN_ORACLE = ROOT / "docs/benchmarks/artifacts/classifier_score_variance_reduction_20260815/gaussian_full/aggregate_result_cpu_v4.json"
EXPECTED_SIR_OBSERVATION_SHA256 = "cd794ad6e90a74f7cf6dc06b33550bff4bef6fbf66bb0917846d0691b5910f07"


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def safe(value):
    if hasattr(value, "numpy"):
        value = value.numpy()
    if hasattr(value, "tolist"):
        value = value.tolist()
    if isinstance(value, dict):
        return {str(k): safe(v) for k, v in value.items()}
    if isinstance(value, (tuple, list)):
        return [safe(v) for v in value]
    if isinstance(value, float) and not math.isfinite(value):
        return None
    return value


def classifier_values():
    values = []
    paths = sorted(CLASSIFIER_ROOT.glob("bundle_*/result.json"))
    if len(paths) != 10:
        raise RuntimeError(f"expected 10 classifier bundles, found {len(paths)}")
    for path in paths:
        payload = json.loads(path.read_text())
        fixed = payload["fixed_outputs"]
        values.append({"bundle": path.parent.name, "j0_T20": float(fixed[0][0]), "fixed_path_sha256": payload["fixed_path_sha256"]})
    return values


def genut_values():
    payload = json.loads(GENUT_RAW.read_text())
    rows = [row for row in payload["rows"] if row.get("model_id") == "austria_sir_T20" and row.get("route") == "repaired_permutation"]
    rows.sort(key=lambda row: int(row["seed"]))
    if len(rows) != len(CLAIM_SEEDS):
        raise RuntimeError(f"expected {len(CLAIM_SEEDS)} repaired-permutation rows, found {len(rows)}")
    return [{"seed": int(row["seed"]), "j0": float(row["score"][0]), "score": row["score"], "finite": bool(row["finite"]), "program_valid": bool(row["program_valid"])} for row in rows]


def law_audit():
    from bayesfilter.independent_score import sir_observation_simulator_tf as sim
    from bayesfilter.highdim.cubature_genut_batch_adapters import parameterized_austria_sir_batch_adapter

    tf.random.set_seed(20260817)
    adapter = parameterized_austria_sir_batch_adapter()
    theta = tf.constant(THETA_VALUES, tf.float64)
    batch_theta = tf.broadcast_to(tf.cast(theta, tf.float32)[None, :], [1, 3])
    states = tf.cast(sim.INITIAL_MEAN[None, :] + tf.random.normal([N, 18], seed=11, dtype=tf.float64), tf.float32)
    noise = tf.cast(tf.random.normal([N, 18], seed=12, dtype=tf.float64), tf.float32)
    adapter_mean = adapter.transition_value(batch_theta, states[None, :, :], noise, tf.constant(0))[0]
    # The standalone simulator uses the same RK4 mean before adding process noise.
    kappa = sim.BASE_KAPPA
    nu = sim.BASE_NU
    simulator_mean = sim._transition_mean(tf.cast(states, tf.float64), kappa, nu)
    mean_diff = tf.reduce_max(tf.abs(tf.cast(adapter_mean - noise[None, :, :][0], tf.float64) - simulator_mean))
    latent = simulator_mean + tf.cast(noise, tf.float64)
    invalid_count = int(tf.reduce_sum(tf.cast(tf.reduce_any(latent[:, 0::2] < 0.0, axis=1), tf.int32)).numpy())
    total_step_paths = N
    state = latent
    for step in range(1, 20):
        step_noise = tf.cast(tf.random.normal([N, 18], seed=100 + step), tf.float64)
        state = sim._transition_mean(state, kappa, nu) + step_noise
        invalid_count += int(tf.reduce_sum(tf.cast(tf.reduce_any(state[:, 0::2] < 0.0, axis=1), tf.int32)).numpy())
        total_step_paths += N
    # Fixed path is generated by the standalone source simulator and is the
    # observation path used by the inherited classifier/GenUT artifacts.
    with tf.device("/CPU:0"):
        observed_cpu = sim.fixed_observed_path(81120, 20)
    observed_gpu = sim.fixed_observed_path(81120, 20)
    gpu_cpu_difference = tf.reduce_max(tf.abs(observed_gpu - observed_cpu))
    return {
        "parameterization": {"kappa": "0.1*exp(theta[0])", "nu": "18*exp(theta[1])", "observation_scale": "10*exp(theta[2])"},
        "max_transition_mean_absolute_difference_fp32_vs_fp64": float(mean_diff.numpy()),
        "transition_mean_match": bool(float(mean_diff.numpy()) < 1.0e-2),
        "transition_precision_note": "GenUT adapter is FP32; standalone simulator is FP64. Difference is recorded as round-off, not treated as a law mismatch.",
        "clipping_probe": {"paths": total_step_paths, "invalid_susceptible_paths": invalid_count, "rate": invalid_count / total_step_paths, "policy_difference_present": True},
        "fixed_observed_path_sha256_cpu": sha_tensor(observed_cpu),
        "fixed_observed_path_sha256_gpu": sha_tensor(observed_gpu),
        "fixed_observed_path_expected_sha256": EXPECTED_SIR_OBSERVATION_SHA256,
        "fixed_observed_path_hash_match": sha_tensor(observed_cpu) == EXPECTED_SIR_OBSERVATION_SHA256,
        "fixed_observed_path_gpu_cpu_max_absolute_difference": float(gpu_cpu_difference.numpy()),
        "fixed_observed_path_shape": [int(x) for x in observed_cpu.shape],
        "finite": bool(tf.reduce_all(tf.math.is_finite(observed_cpu)).numpy() and tf.reduce_all(tf.math.is_finite(observed_gpu)).numpy()),
    }


def sha_tensor(value: tf.Tensor) -> str:
    return hashlib.sha256(tf.io.serialize_tensor(value).numpy()).hexdigest()


def summary(values, key):
    xs = [float(row[key]) for row in values]
    mean = statistics.mean(xs)
    sd = statistics.stdev(xs) if len(xs) > 1 else 0.0
    return {"count": len(xs), "mean": mean, "sample_sd": sd, "min": min(xs), "max": max(xs), "positive_count": sum(x > 0 for x in xs), "negative_count": sum(x < 0 for x in xs)}


def run(output: Path):
    started = time.perf_counter()
    from bayesfilter.runtime.gpu_memory_policy import configure_tensorflow_gpu_memory_growth

    memory_policy = configure_tensorflow_gpu_memory_growth(tf, require_gpu=True)
    tf.config.set_soft_device_placement(False)
    physical_gpus = tf.config.list_physical_devices("GPU")
    logical_gpus = tf.config.list_logical_devices("GPU")
    if not logical_gpus:
        raise RuntimeError("trusted GPU run requires a visible logical GPU")
    gpu_details = []
    for device in physical_gpus:
        details = tf.config.experimental.get_device_details(device)
        gpu_details.append({"physical_device": device.name, "device_name": details.get("device_name"), "compute_capability": details.get("compute_capability")})
    for path in (GENUT_RAW, LGSSM_ORACLE, GAUSSIAN_ORACLE):
        if not path.exists():
            raise FileNotFoundError(path)
    law = law_audit()
    classifier = classifier_values()
    genut = genut_values()
    upstream = {
        "classifier_gaussian_exact_oracle": "FAILED_UPSTREAM_8_OF_9_CELLS",
        "genut_lgssm_exact_oracle": "FAILED_UPSTREAM_MATERIAL_KALMAN_VALUE_AND_SCORE_ERRORS",
    }
    classifier_summary = summary(classifier, "j0_T20")
    genut_summary = summary(genut, "j0")
    payload = {
        "schema": "bayesfilter.genut_sir_j0_common_target_validation.v1",
        "status": "COMPLETE_DIAGNOSTIC",
        "target": {"model": "Austria-SIR", "horizon": 20, "coordinate": "j0", "theta": list(THETA_VALUES), "particle_count_genut": 1008, "classifier_holdout_bundles": 10},
        "law_audit": law,
        "classifier_holdout": {"source_root": str(CLASSIFIER_ROOT.relative_to(ROOT)), "source_sha256": sha(CLASSIFIER_ROOT / "bundle_00/result.json"), "rows": classifier, "summary": classifier_summary},
        "genut_repaired_permutation": {"source": str(GENUT_RAW.relative_to(ROOT)), "source_sha256": sha(GENUT_RAW), "rows": genut, "summary": genut_summary},
        "upstream_vetoes": upstream,
        "decision": {
            "simulator_law_match": law["transition_mean_match"] and law["finite"] and law["fixed_observed_path_hash_match"],
            "clipping_rate": law["clipping_probe"]["rate"],
            "classification": "genut_finite_program_or_score_error_candidate_with_classifier_uncertainty" if law["transition_mean_match"] and law["fixed_observed_path_hash_match"] else "simulator_law_mismatch_candidate",
            "ranking_supported": False,
            "score_correctness_established": False,
        },
        "run_manifest": {"command": sys.argv, "environment": "/home/chakwong/anaconda3/envs/tftwogpu", "python": sys.executable, "tensorflow": tf.__version__, "host": platform.node(), "dtype": "simulator_fp64_genut_adapter_fp32", "gpu": gpu_details, "memory_policy": dict(memory_policy), "seeds": list(CLAIM_SEEDS), "wall_time_seconds": time.perf_counter() - started, "source_hashes": {str(path.resolve().relative_to(ROOT)): sha(path.resolve()) for path in (Path(__file__), GENUT_RAW, LGSSM_ORACLE, GAUSSIAN_ORACLE)}},
        "nonclaims": ["classifier is not exact-oracle admitted", "GenUT score is not correct", "no method superiority or HMC/default readiness", "clipping probe is diagnostic and not a full particle-cloud proof"],
    }
    output.mkdir(parents=True, exist_ok=False)
    (output / "result.json").write_text(json.dumps(safe(payload), indent=2, sort_keys=True) + "\n")
    md = ["# GenUT/SIR `j0` Common-Target Validation", "", f"- status: `{payload['status']}`", f"- FP32/FP64 transition max difference: `{law['max_transition_mean_absolute_difference_fp32_vs_fp64']:.6g}`", f"- clipping probe invalid rate: `{law['clipping_probe']['rate']:.6g}`", f"- CPU fixed-path hash match: `{law['fixed_observed_path_hash_match']}`", f"- GPU/CPU fixed-path max difference: `{law['fixed_observed_path_gpu_cpu_max_absolute_difference']:.6g}`", "", "| Source | Mean j0 | SD | Positive | Negative |", "|---|---:|---:|---:|---:|", f"| Classifier holdout bundles | {classifier_summary['mean']:.6g} | {classifier_summary['sample_sd']:.6g} | {classifier_summary['positive_count']} | {classifier_summary['negative_count']} |", f"| GenUT repaired permutation seeds | {genut_summary['mean']:.6g} | {genut_summary['sample_sd']:.6g} | {genut_summary['positive_count']} | {genut_summary['negative_count']} |", "", f"- classification: `{payload['decision']['classification']}`", "- exact score correctness remains unestablished."]
    (output / "result.md").write_text("\n".join(md) + "\n")
    print(json.dumps({"status": payload["status"], "output": str(output), "classification": payload["decision"]["classification"]}, indent=2))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    run(args.output.resolve())


if __name__ == "__main__":
    main()
