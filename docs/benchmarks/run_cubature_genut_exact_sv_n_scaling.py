#!/usr/bin/env python3
"""Historical non-DGP engineering scaling diagnostic.

The direct-Normal transformed observations are not generated by the SV DGP.
This route is ineligible for SV accuracy or scaling evidence and fails closed
unless explicitly requested as historical engineering-only work.
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import subprocess
import sys
import time
from pathlib import Path

os.environ.setdefault("TF_FORCE_GPU_ALLOW_GROWTH", "true")
ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import tensorflow as tf


T_VALUES = (2, 10, 50)
N_VALUES = (12, 48, 96)
SEEDS = tuple(range(3340, 3356))
CONTROLS = {"epsilon": 2.0, "sinkhorn_steps": 8, "ridge": 1.0e-4}
VALUE_BUDGET = 0.25


def _obs(horizon):
    with tf.device("/CPU:0"):
        return tf.random.stateless_normal([horizon, 1], [8000 + horizon, 9], dtype=tf.float32)


def _inputs(n, horizon, seed):
    with tf.device("/CPU:0"):
        initial = tf.random.stateless_normal([n, 1], [seed, 201], dtype=tf.float32)
        process = tf.random.stateless_normal([horizon, n, 1], [seed, 202], dtype=tf.float32)
        design = tf.repeat(tf.constant([[1.0], [-1.0]], tf.float32), repeats=n // 2, axis=0)
    return initial, process, design


def _dense_value(observations, theta):
    from bayesfilter.highdim.sv_mixture_cut4 import ExactTransformedSVSSM, exact_transformed_sv_scalar_dense_reference

    return exact_transformed_sv_scalar_dense_reference(
        ExactTransformedSVSSM(sigma=1.0),
        tf.cast(theta, tf.float64),
        tf.exp(0.5 * tf.cast(observations, tf.float64)),
        order=257,
        radius=8.0,
    ).log_likelihood


def run(
    output_root: Path,
    *,
    n_values: tuple[int, ...] = N_VALUES,
    t_values: tuple[int, ...] = T_VALUES,
    seeds: tuple[int, ...] = SEEDS,
    historical_nondgp_engineering_only: bool = False,
):
    if not historical_nondgp_engineering_only:
        raise RuntimeError(
            "revoked non-DGP fixture: use a declared SV-DGP dataset; "
            "historical mechanics require --historical-nondgp-engineering-only"
        )
    started = time.perf_counter()
    physical = tf.config.list_physical_devices("GPU")
    if not physical:
        raise RuntimeError("N scaling requires a visible GPU")
    tf.config.set_soft_device_placement(False)
    from bayesfilter.runtime.gpu_memory_policy import configure_tensorflow_gpu_memory_growth
    memory_policy = configure_tensorflow_gpu_memory_growth(tf, require_gpu=True)
    tf.config.experimental.enable_tensor_float_32_execution(True)
    from bayesfilter.highdim.cubature_genut_adapters import exact_transformed_sv_candidate_adapter
    from bayesfilter.highdim.cubature_genut_filter import finite_value_score

    adapter = exact_transformed_sv_candidate_adapter()
    theta = tf.constant([0.25, -0.15], tf.float32)
    rows = []
    for n in n_values:
        if n < 2 or n % 2 != 0:
            raise ValueError("scalar Cubature particle count must be divisible by 2")
        @tf.function(jit_compile=True, reduce_retracing=True)
        def evaluate(theta_, observations_, initial_, process_, design_):
            with tf.device("/GPU:0"):
                return finite_value_score(
                    adapter, theta_, observations_, initial_, process_, design_, **CONTROLS
                )
        for horizon in t_values:
            observations = _obs(horizon)
            dense = _dense_value(observations, theta)
            for seed in seeds:
                initial, process, design = _inputs(n, horizon, seed)
                try:
                    tf.config.experimental.reset_memory_stats("GPU:0")
                except (AttributeError, RuntimeError, tf.errors.InvalidArgumentError):
                    pass
                cell_started = time.perf_counter()
                value, score, diagnostics = evaluate(theta, observations, initial, process, design)
                memory = tf.config.experimental.get_memory_info("GPU:0")
                device = str(value.device)
                rows.append({
                    "N": n,
                    "T": horizon,
                    "seed": seed,
                    "value_error_to_dense": float((value - tf.cast(dense, tf.float32)).numpy()),
                    "score": [float(x) for x in score.numpy().tolist()],
                    "max_row_residual": float(diagnostics["max_row_residual"].numpy()),
                    "max_col_residual": float(diagnostics["max_col_residual"].numpy()),
                    "finite": bool(tf.math.is_finite(value).numpy()) and bool(tf.reduce_all(tf.math.is_finite(score)).numpy()),
                    "elapsed_seconds": time.perf_counter() - cell_started,
                    "device": device,
                    "gpu_placement": "GPU" in device.upper(),
                    "gpu_allocator": {key: int(item) for key, item in memory.items()},
                })
    summary = []
    for n in n_values:
        for horizon in t_values:
            cell = [row for row in rows if row["N"] == n and row["T"] == horizon]
            errors = [row["value_error_to_dense"] for row in cell]
            score_columns = list(zip(*(row["score"] for row in cell)))
            summary.append({
                "N": n,
                "T": horizon,
                "max_abs_value_error": max(abs(x) for x in errors),
                "mean_value_error": sum(errors) / len(errors),
                "score_sd": [float(tf.math.reduce_std(tf.constant(column, tf.float32)).numpy()) for column in score_columns],
                "engineering_valid": all(
                    row["finite"]
                    and row["gpu_placement"]
                    and row["max_row_residual"] < 1.0e-2
                    and row["max_col_residual"] < 1.0e-2
                    for row in cell
                ),
                "target_accuracy_valid": False,
                "hard_valid": False,
            })
    payload = {
        "schema_version": "bayesfilter.cubature_genut_exact_sv_n_scaling.v1",
        "campaign_id": "cubature-genut-exact-sv-n-scaling-20260721",
        "physical_devices": [item.name for item in physical],
        "memory_policy": dict(memory_policy),
        "dtype": "float32",
        "tf32_enabled": True,
        "jit_compile": True,
        "controls": CONTROLS,
        "n_values": list(n_values),
        "t_values": list(t_values),
        "seeds": list(seeds),
        "rows": rows,
        "summary": summary,
        "engineering_valid": all(item["engineering_valid"] for item in summary),
        "scientific_eligibility": "ineligible_nondgp_engineering_only",
        "target_accuracy_valid": False,
        "score_accuracy_valid": False,
        "hard_valid": False,
        "target_error_budget": VALUE_BUDGET,
        "comparator": {"status": "BLOCKED_SAME_TARGET_COMPARATOR"},
        "run_manifest": {
            "git_commit": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(),
            "command": list(sys.argv),
            "python": sys.version,
            "tensorflow": tf.__version__,
            "wall_seconds": time.perf_counter() - started,
        },
        "nonclaims": [
            "historical non-DGP engineering mechanics only",
            "wrong and irrelevant for SV accuracy, bias, tuning, score, or scaling",
            "no method ranking or leaderboard/default admission",
        ],
    }
    output_root.mkdir(parents=True, exist_ok=False)
    (output_root / "result.json").write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    print(json.dumps({"output": str(output_root), "hard_valid": payload["hard_valid"]}, indent=2))
    return payload


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-root", type=Path, required=True)
    parser.add_argument("--n-values", nargs="+", type=int, default=list(N_VALUES))
    parser.add_argument("--t-values", nargs="+", type=int, default=list(T_VALUES))
    parser.add_argument("--seeds", nargs="+", type=int, default=list(SEEDS))
    parser.add_argument("--historical-nondgp-engineering-only", action="store_true")
    args = parser.parse_args()
    run(
        args.output_root.resolve(),
        n_values=tuple(args.n_values),
        t_values=tuple(args.t_values),
        seeds=tuple(args.seeds),
        historical_nondgp_engineering_only=args.historical_nondgp_engineering_only,
    )
