def deterministic_candidate_order(
    candidates: Sequence[Any],
    *,
    anchor_l: int,
) -> tuple[Any, ...]:
    """Order an already-qualified arbitrary candidate set without ranking evidence.

    This is a policy tie-break for candidate sets that were not generated by
    ``fixed_trajectory_candidate_values``.  It reads only the declared
    ``num_leapfrog_steps`` (or ``L``) and immutable ``signature`` fields.  It
    must be called only after candidate-local and shared hard screens pass.
    Acceptance, ESS, runtime, ESJD, and other stochastic diagnostics are never
    consulted.
    """

    anchor = _strict_integer(anchor_l, name="anchor_l", minimum=1)
    items = tuple(candidates)
    if not items:
        return ()

    def key(item: Any) -> tuple[int, int, str]:
        if isinstance(item, Mapping):
            raw_l = item.get("num_leapfrog_steps", item.get("L"))
            raw_signature = item.get("signature")
        else:
            raw_l = getattr(item, "num_leapfrog_steps", getattr(item, "L", None))
            raw_signature = getattr(item, "signature", None)
        leapfrog = _strict_integer(raw_l, name="candidate num_leapfrog_steps", minimum=1)
        signature = str(raw_signature)
        if not signature:
            raise ValueError("candidate signature must be nonempty")
        return (abs(leapfrog - anchor), leapfrog, signature)

    ordered = tuple(sorted(items, key=key))
    if len({key(item) for item in ordered}) != len(ordered):
        raise ValueError("candidate tie-break keys must be unique")
    return ordered


@dataclass(frozen=True)
class VerifiedFixedKernelHandoff:
    """BayesFilter-owned handoff for one independently verified fixed pair."""

    num_leapfrog_steps: int
    step_size: float
    source_candidate_signature: str
    lineage_signature: str
    verification_checkpoint_sha256: str
    anchor_l: int

    def __post_init__(self) -> None:
        leapfrog = _strict_integer(
            self.num_leapfrog_steps,
            name="num_leapfrog_steps",
            minimum=1,
        )
        anchor = _strict_integer(self.anchor_l, name="anchor_l", minimum=1)
        step = float(self.step_size)
        if not np.isfinite(step) or step <= 0.0:
            raise ValueError("verified fixed-kernel step_size must be positive and finite")
        for name in (
            "source_candidate_signature",
            "lineage_signature",
            "verification_checkpoint_sha256",
        ):
            value = str(getattr(self, name))
            if not value:
                raise ValueError(f"{name} must be nonempty")
            if name == "verification_checkpoint_sha256" and (
                len(value) != 64 or any(char not in "0123456789abcdef" for char in value)
            ):
                raise ValueError("verification_checkpoint_sha256 must be lowercase SHA-256")
            object.__setattr__(self, name, value)
        object.__setattr__(self, "num_leapfrog_steps", leapfrog)
        object.__setattr__(self, "anchor_l", anchor)
        object.__setattr__(self, "step_size", step)

    @property
    def signature(self) -> str:
        return _signature("bayesfilter.hmc_verified_fixed_kernel_handoff.v1", self.payload())

    def payload(self) -> Mapping[str, Any]:
        return {
            "schema": "bayesfilter.hmc_verified_fixed_kernel_handoff.v1",
            "num_leapfrog_steps": self.num_leapfrog_steps,
            "step_size": self.step_size,
            "source_candidate_signature": self.source_candidate_signature,
            "lineage_signature": self.lineage_signature,
            "verification_checkpoint_sha256": self.verification_checkpoint_sha256,
            "selection_rule": "closest_to_anchor_then_lower_l_then_candidate_signature",
            "anchor_l": self.anchor_l,
            "stochastic_ranking_performed": False,
            "exact_pair_reverified_without_retuning": True,
            "retained_sampling_authorized": False,
            "nonclaims": (
                "fixed-kernel qualification handoff only",
                "policy tie-break is not stochastic ranking",
                "no convergence or posterior-validity claim",
                "no retained-sampling authorization",
            ),
        }


def build_verified_fixed_kernel_handoff(
    candidates: Sequence[Mapping[str, Any]],
    *,
    anchor_l: int,
) -> VerifiedFixedKernelHandoff | None:
    """Choose from hard-screen-passed candidates using policy fields only."""

    normalized = tuple(candidates)
    if not normalized:
        return None
    for candidate in normalized:
        if candidate.get("qualification_passed") is not True:
            raise ValueError("verified handoff accepts only hard-screen-passed candidates")
    selected = deterministic_candidate_order(normalized, anchor_l=anchor_l)[0]
    return VerifiedFixedKernelHandoff(
        num_leapfrog_steps=selected.get("num_leapfrog_steps", selected.get("L")),
        step_size=selected.get("step_size"),
        source_candidate_signature=selected.get("signature"),
        lineage_signature=selected.get("lineage_signature"),
        verification_checkpoint_sha256=selected.get(
            "verification_checkpoint_sha256"
        ),
        anchor_l=anchor_l,
    )

