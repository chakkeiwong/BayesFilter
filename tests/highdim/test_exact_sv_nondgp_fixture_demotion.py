from __future__ import annotations

import json
from pathlib import Path

import pytest

from docs.benchmarks import run_cubature_exact_sv_score_ladder as score_ladder
from docs.benchmarks import run_cubature_genut_exact_sv_claim_diagnostic as claim
from docs.benchmarks import run_cubature_genut_exact_sv_n_scaling as scaling
from docs.benchmarks import run_exact_sv_fixed_gaussian_genut_paired as paired


ROOT = Path(__file__).resolve().parents[2]
CORRECTION = (
    ROOT
    / "docs/plans/bayesfilter-exact-sv-nondgp-fixture-demotion-correction-2026-07-22.md"
)


@pytest.mark.parametrize(
    "call",
    [
        lambda path: claim.run(path),
        lambda path: scaling.run(path),
        lambda path: score_ladder.run(path),
    ],
)
def test_revoked_nondgp_runners_fail_before_execution(tmp_path: Path, call) -> None:
    output = tmp_path / "must_not_exist"
    with pytest.raises(RuntimeError, match="revoked non-DGP fixture"):
        call(output)
    assert not output.exists()


