def test_correction_artifact_excludes_original_dataset() -> None:
    payload = json.loads(
        (
            ROOT
            / "docs/benchmarks/artifacts/"
            "exact_sv_fixed_gaussian_genut_paired_20260721/"
            "correction_20260722.json"
        ).read_text(encoding="utf-8")
    )
    assert payload["scientifically_eligible_dataset_keys"] == ["fresh_dgp"]
    assert set(payload["scientifically_ineligible_dataset_keys"]) == {"original"}
    assert payload["revoked_source_field"] == "mechanism_support"
    assert CORRECTION.exists()


